const messages = { en, fr, es } as const;

export function readStoredLocale(): Locale {
	if (typeof localStorage === "undefined") {
		return "fr";
	}
	const saved = localStorage.getItem(STORAGE_KEY);
	return saved === "fr" || saved === "es" || saved === "en" ? saved : "fr";
}

export function translate(locale: Locale, key: string, values?: Record<string, string | number>) {
	const table = messages[locale] as Record<string, string>;
	const fallback = en as Record<string, string>;
	return (table[key] ?? fallback[key] ?? key).replace(/\{(\w+)\}/g, (_, name: string) =>
		String(values?.[name] ?? `{${name}}`),
	);
}

export function catalogKeys(): string[] {
	return Object.keys(en);
}

type I18n = { locale: Locale; setLocale: (locale: Locale) => void; t: Translate };
const I18nContext = createContext<I18n | null>(null);
export function I18nProvider({ children }: { children: ReactNode }) {
	const [locale, setLocale] = useState<Locale>(() => readStoredLocale());
	useEffect(() => {
		localStorage.setItem(STORAGE_KEY, locale);
		document.documentElement.lang = locale;
	}, [locale]);
	const value = useMemo(
		() => ({
			locale,
			setLocale,
			t: (key: string, values?: Record<string, string | number>) => translate(locale, key, values),
		}),
		[locale],
	);
	return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}
export function useI18n(): I18n {
	const value = useContext(I18nContext);
	if (value === null) throw new Error("useI18n must be used inside I18nProvider");
	return value;
}
